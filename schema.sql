create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 display_name text,
 role text not null default 'customer' check (role in ('customer','owner')),
 created_at timestamptz not null default now()
);
create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path='' as $$
begin
 insert into public.profiles(id,display_name) values(new.id,coalesce(new.raw_user_meta_data->>'full_name','KINZE Customer')) on conflict(id) do nothing;
 return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();
create or replace function public.is_kinze_owner() returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.profiles where id=(select auth.uid()) and role='owner');
$$;
create table if not exists public.products(
 id bigint generated by default as identity primary key, name text not null, category text not null default 'Other',
 description text not null default '', price_pkr numeric(12,2) not null check(price_pkr>=0),
 emoji text not null default '✦', product_url text not null default '', is_active boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.cart_items(
 user_id uuid not null references auth.users(id) on delete cascade,
 product_id bigint not null references public.products(id) on delete cascade,
 quantity integer not null default 1 check(quantity between 1 and 99),
 updated_at timestamptz not null default now(), primary key(user_id,product_id)
);
create table if not exists public.wishlist_items(
 user_id uuid not null references auth.users(id) on delete cascade,
 product_id bigint not null references public.products(id) on delete cascade,
 created_at timestamptz not null default now(), primary key(user_id,product_id)
);
create table if not exists public.orders(
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete restrict,
 full_name text not null, phone text not null, delivery_address text not null,
 total_pkr numeric(12,2) not null check(total_pkr>=0),
 status text not null default 'received' check(status in ('received','reviewing','completed','cancelled')),
 created_at timestamptz not null default now()
);
create table if not exists public.order_items(
 id bigint generated by default as identity primary key,
 order_id bigint not null references public.orders(id) on delete cascade,
 product_id bigint references public.products(id) on delete set null,
 product_name text not null, unit_price_pkr numeric(12,2) not null, quantity integer not null check(quantity>0)
);
alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.cart_items enable row level security;
alter table public.wishlist_items enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
drop policy if exists "Profiles visible to self or owner" on public.profiles;
create policy "Profiles visible to self or owner" on public.profiles for select to authenticated using(id=(select auth.uid()) or public.is_kinze_owner());
drop policy if exists "Active products are public" on public.products;
create policy "Active products are public" on public.products for select to anon,authenticated using(is_active=true or public.is_kinze_owner());
drop policy if exists "Owner manages products" on public.products;
create policy "Owner manages products" on public.products for all to authenticated using(public.is_kinze_owner()) with check(public.is_kinze_owner());
drop policy if exists "Customers manage own cart" on public.cart_items;
create policy "Customers manage own cart" on public.cart_items for all to authenticated using(user_id=(select auth.uid())) with check(user_id=(select auth.uid()));
drop policy if exists "Customers manage own wishlist" on public.wishlist_items;
create policy "Customers manage own wishlist" on public.wishlist_items for all to authenticated using(user_id=(select auth.uid())) with check(user_id=(select auth.uid()));
drop policy if exists "Customers and owner view orders" on public.orders;
create policy "Customers and owner view orders" on public.orders for select to authenticated using(user_id=(select auth.uid()) or public.is_kinze_owner());
drop policy if exists "Owner updates orders" on public.orders;
create policy "Owner updates orders" on public.orders for update to authenticated using(public.is_kinze_owner()) with check(public.is_kinze_owner());
drop policy if exists "Order items visible to order owner or KINZE owner" on public.order_items;
create policy "Order items visible to order owner or KINZE owner" on public.order_items for select to authenticated using(exists(select 1 from public.orders o where o.id=order_id and (o.user_id=(select auth.uid()) or public.is_kinze_owner())));
create or replace function public.kinze_place_order(p_full_name text,p_phone text,p_delivery_address text)
returns bigint language plpgsql security invoker set search_path='' as $$
declare v_user uuid:=auth.uid(); v_order_id bigint; v_total numeric(12,2); v_count integer;
begin
 if v_user is null then raise exception 'Please sign in before placing an order.'; end if;
 if coalesce(trim(p_full_name),'')='' or coalesce(trim(p_phone),'')='' or coalesce(trim(p_delivery_address),'')='' then raise exception 'Complete your name, phone and delivery address.'; end if;
 select count(*),coalesce(sum(c.quantity*p.price_pkr),0) into v_count,v_total from public.cart_items c join public.products p on p.id=c.product_id where c.user_id=v_user and p.is_active=true;
 if v_count=0 then raise exception 'Your cart is empty.'; end if;
 insert into public.orders(user_id,full_name,phone,delivery_address,total_pkr) values(v_user,trim(p_full_name),trim(p_phone),trim(p_delivery_address),v_total) returning id into v_order_id;
 insert into public.order_items(order_id,product_id,product_name,unit_price_pkr,quantity) select v_order_id,p.id,p.name,p.price_pkr,c.quantity from public.cart_items c join public.products p on p.id=c.product_id where c.user_id=v_user and p.is_active=true;
 delete from public.cart_items where user_id=v_user; return v_order_id;
end; $$;
grant execute on function public.kinze_place_order(text,text,text) to authenticated;
